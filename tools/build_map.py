import json
import math
import sys

SRC, OUT = sys.argv[1], sys.argv[2]

LAMBDA0 = 100.0
PHI0, PHI1 = 52.0, 66.0
WIDTH = 1000.0
PAD = 12.0
SPACING = 8.0
R_MAX, R_MIN = 2.5, 1.05
EDGE_FADE = 22.0

rad = math.radians
sy0 = math.sin(rad(PHI0))
n = (sy0 + math.sin(rad(PHI1))) / 2
c = 1 + sy0 * (2 * n - sy0)
r0 = math.sqrt(c) / n

def raw(lon, lat):
    lam = lon - LAMBDA0
    lam = (lam + 180) % 360 - 180
    lam, phi = rad(lam), rad(lat)
    r = math.sqrt(max(0.0, c - 2 * n * math.sin(phi))) / n
    return r * math.sin(lam * n), r0 - r * math.cos(lam * n)

with open(SRC, encoding="utf-8") as fh:
    topo = json.load(fh)

sx, sy = topo["transform"]["scale"]
tx0, ty0 = topo["transform"]["translate"]
arcs = []
for arc in topo["arcs"]:
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx
        y += dy
        pts.append((x * sx + tx0, y * sy + ty0))
    arcs.append(pts)

def ring_coords(ring):
    out = []
    for idx in ring:
        pts = arcs[idx] if idx >= 0 else arcs[~idx][::-1]
        out.extend(pts if not out else pts[1:])
    return out

geom = next(g for g in topo["objects"]["countries"]["geometries"] if g.get("id") == "643")
polys = geom["arcs"] if geom["type"] == "MultiPolygon" else [geom["arcs"]]
rings_ll = [[ring_coords(r) for r in poly] for poly in polys]

raw_rings = [[[raw(lon, lat) for lon, lat in ring] for ring in poly] for poly in rings_ll]
xs = [p[0] for poly in raw_rings for ring in poly for p in ring]
ys = [p[1] for poly in raw_rings for ring in poly for p in ring]
k = (WIDTH - 2 * PAD) / (max(xs) - min(xs))
tx = PAD - k * min(xs)
ty = PAD + k * max(ys)
HEIGHT = round(k * (max(ys) - min(ys)) + 2 * PAD)

def screen(p):
    return tx + k * p[0], ty - k * p[1]

rings = [[[screen(p) for p in ring] for ring in poly] for poly in raw_rings]

def inside_ring(x, y, ring):
    hit = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i]
        xj, yj = ring[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit

def inside(x, y):
    for poly in rings:
        if inside_ring(x, y, poly[0]) and not any(inside_ring(x, y, h) for h in poly[1:]):
            return True
    return False

CELL = EDGE_FADE
grid = {}
for poly in rings:
    for ring in poly:
        for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]):
            steps = max(1, int(math.hypot(x2 - x1, y2 - y1) / 3))
            for s in range(steps):
                t = s / steps
                bx, by = x1 + (x2 - x1) * t, y1 + (y2 - y1) * t
                grid.setdefault((int(bx // CELL), int(by // CELL)), []).append((bx, by))

def coast_distance(x, y):
    gx, gy = int(x // CELL), int(y // CELL)
    best = EDGE_FADE
    for ix in (gx - 1, gx, gx + 1):
        for iy in (gy - 1, gy, gy + 1):
            for bx, by in grid.get((ix, iy), ()):
                d = math.hypot(bx - x, by - y)
                if d < best:
                    best = d
    return best

dots = []
row = 0
y = PAD
while y < HEIGHT - PAD + SPACING:
    offset = (SPACING / 2) if row % 2 else 0.0
    x = PAD + offset
    while x < WIDTH - PAD + SPACING:
        if inside(x, y):
            t = min(1.0, coast_distance(x, y) / EDGE_FADE)
            r = R_MIN + (R_MAX - R_MIN) * (t ** 0.8)
            dots.append((round(x, 1), round(y, 1), round(r, 2)))
        x += SPACING
    y += SPACING * 0.866
    row += 1

for poly in rings:
    outer = poly[0]
    bx = [p[0] for p in outer]
    by = [p[1] for p in outer]
    w, h = max(bx) - min(bx), max(by) - min(by)
    if w < SPACING * 1.5 and h < SPACING * 1.5 and (w > 2.5 or h > 2.5):
        cx, cy = sum(bx) / len(bx), sum(by) / len(by)
        if all(math.hypot(cx - d[0], cy - d[1]) > SPACING * 0.8 for d in dots):
            dots.append((round(cx, 1), round(cy, 1), R_MIN))

data = {
    "source": "Natural Earth 1:50m via world-atlas@2.0.2",
    "width": WIDTH,
    "height": HEIGHT,
    "projection": {"lambda0": LAMBDA0, "phi0": PHI0, "phi1": PHI1, "k": round(k, 4), "tx": round(tx, 4), "ty": round(ty, 4)},
    "spacing": SPACING,
    "dots": dots,
}

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("// Generated by tools/build_map.py. Do not edit by hand.\n")
    fh.write("window.RU_MAP = ")
    json.dump(data, fh, separators=(",", ":"), ensure_ascii=False)
    fh.write(";\n")

print(f"{len(dots)} dots, viewBox {WIDTH:.0f}x{HEIGHT}")
